class TextCleaningSlotHandler(SlotHandler):
    """文本清洗处理器"""

    def __init__(self, next_handler=None):
        super().__init__(next_handler)

    def handle(self, context: Dict[str, Any]) -> Dict[str, Any]:
        # 清洗输入文本
        context['cleaned_text'] = self._clean_input(context['input_text'])
        return super().handle(context)

    def _clean_input(self, text):
        """清洗用户输入文本

        Args:
            text: 原始输入字符串

        Returns:
            str: 清洗后的字符串
        """
        if not text:
            return ""

        # 去除首尾空白字符
        text = text.strip()

        # 繁简转换
        text = self._convert_traditional_to_simplified(text)

        # 转换为小写（统一大小写）
        text = text.lower()

        # 数字转换（中文数字转阿拉伯数字）
        text = self._convert_chinese_numbers(text)

        # 限制最大长度（防止恶意或异常输入）
        if len(text) > self.max_length:
            logger.info(f"输入超过最大长度限制 {self.max_length}，已截断")
            return text[:self.max_length]

        return text

    def _convert_traditional_to_simplified(self, text):
        """繁体中文转换为简体中文

        Args:
            text: 输入文本

        Returns:
            str: 转换后的文本
        """
        try:
            # 繁简转换映射表（常用字）


            # 执行繁简转换
            for traditional, simplified in traditional_to_simplified.items():
                text = text.replace(traditional, simplified)

            return text
        except Exception as e:
            logger.warning(f"繁简转换失败: {e}")
            return text

    def _convert_chinese_numbers(self, text):
        """将中文数字转换为阿拉伯数字

        Args:
            text: 输入文本

        Returns:
            str: 转换后的文本
        """
        # 中文数字映射表
        chinese_to_arabic = {
            '零': '0', '一': '1', '二': '2', '三': '3', '四': '4',
            '五': '5', '六': '6', '七': '7', '八': '8', '九': '9',
            '十': '10', '百': '100', '千': '1000', '万': '10000'
        }

        # 简单替换，处理常见的中文数字
        for chinese, arabic in chinese_to_arabic.items():
            # 对于单位词（十、百、千、万），需要特殊处理
            if chinese in ['十', '百', '千', '万']:
                continue
            text = text.replace(chinese, arabic)

        # 处理"十"的特殊情况
        text = self._convert_chinese_ten(text)

        return text

    def _convert_chinese_ten(self, text):
        """处理中文"十"的转换

        Args:
            text: 输入文本

        Returns:
            str: 转换后的文本
        """
        import re

        # 处理"十几"的情况，如"十五"转为"15"
        pattern = r'(\d*?)十(\d?)'
        def replace_ten(match):
            tens = match.group(1) or '1'  # 如果十前面没有数字，默认为1（如"十五"->"15"）
            units = match.group(2) or '0'  # 如果十后面没有数字，默认为0（如"二十"->"20"）
            return str(int(tens) * 10 + int(units)) if tens and units else f"{tens}0"

        text = re.sub(pattern, replace_ten, text)
        return text
